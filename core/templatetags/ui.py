@register.simple_tag
def icon(name, size=18, cls=""):
    body = ICONS.get(name, ICONS["file"])
    return format_html(
        '<svg class="icon {}" width="{}" height="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{}</svg>',
        cls, size, size, mark_safe(body),
    )


@register.filter
def money(value):
    if value in (None, ""):
        return "—"
    try:
        return f"{Decimal(value):,.2f}"
    except Exception:
        return value


@register.filter
def num(value):
    if value in (None, ""):
        return ""
    try:
        d = Decimal(value)
        return f"{d:.2f}"
    except Exception:
        return value


@register.filter
def dtlocal(value):
    """Format for <input type=datetime-local>."""
    if not value:
        return ""
    return timezone.localtime(value).strftime("%Y-%m-%dT%H:%M")


@register.filter
def dtshow(value):
    if not value:
        return "—"
    return timezone.localtime(value).strftime("%d/%m/%Y %I:%M %p")


@register.filter
def get_item(d, key):
    try:
        return d.get(key)
    except AttributeError:
        return None


@register.filter
def issue_fields(issues):
    return {i.get("field") for i in issues or [] if i.get("level") in ("error", "warning")}


@register.filter
def workflow_class(value):
    return {
        "approved": "ok", "exported": "info", "extracted": "info", "awaiting_review": "warn",
        "rejected": "bad", "failed": "bad", "pending": "muted",
    }.get(value, "muted")


@register.simple_tag(takes_context=True)
def qs_replace(context, **kwargs):
    params = context["request"].GET.copy()
    for k, v in kwargs.items():
        if v in (None, ""):
            params.pop(k, None)
        else:
            params[k] = v
    params.pop("page", None) if "page" not in kwargs else None
    return params.urlencode()
